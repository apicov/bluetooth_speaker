def zab_seconds(binary, wav, window=1.0):
    """
    @brief Per-window statistics for splitting a recording into drumming and
           talking.

    Three numbers, all from Frame::band so that nothing here can measure
    something a satellite could not -- a rule, not a coincidence:

      b0    median band 0, the mallet stroke's own band
      rise  p90 of the frame-to-frame rise in band 0: transients rather than
            level, which is what separates drumming from a sustained low note
      b1    median band 1, where a voice's vowels are
      b2    median band 2, where a voice's consonants are and where the drum
            has almost nothing

    A drum passage is high `rise`; a talking passage is low `rise` with band 1
    still present, which also separates talking from the silence between
    takes. Level alone would not do it, since a ringing drum head and a
    speaking voice can share a band-0 median. b2 is the obvious choice for the
    speech half and is the wrong one: on these recordings it barely moves
    whether anyone is talking or not, while b1 moves by a factor of ten.

    @param binary  Which pattern_lab build to run.
    @param wav     The recording.
    @param window  Seconds per window.
    @return One dict per window: t, b0, b1, b2, rise.
    """
    with tempfile.TemporaryDirectory() as td:
        prefix = Path(td) / "seg"
        run_dump(binary, wav, prefix)
        meta, band = read_band_dump(prefix)
    hop, rate = int(meta["hop"]), int(meta["rate"])
    per = max(1, int(window * rate / hop))
    out = []
    for i in range(0, len(band), per):
        w = band[i:i + per]
        if len(w) < per // 2:
            break
        rises = [max(0.0, w[j][0] - w[j - 1][0]) for j in range(1, len(w))]
        out.append({
            "t": i * hop / rate,
            "b0": pctile([f[0] for f in w], 0.50),
            "b1": pctile([f[1] for f in w], 0.50),
            "b2": pctile([f[2] for f in w], 0.50),
            "rise": pctile(rises, 0.90),
        })
    return out


def cmd_segments(args):
    """
    @brief Propose the segment table, for a human to confirm by ear.

    Proposed rather than written: this classifier finds the boundaries, it is
    not evidence for them. What gets checked into ZAB_SEGMENTS is what a
    person confirmed, and that distinction is the point -- a tuning input with
    no provenance is worth nothing.

    Short interruptions inside a run are absorbed, since a bar's rest inside a
    groove is not a segment boundary and one struck drum inside a sentence is
    not a drum segment.

    @param args  Parsed arguments: hop, window, the rise and b1 thresholds,
                 the minimum run and segment lengths, and raw.
    """
    lab = build_lab(args.hop)
    print("# proposed segments -- confirm by ear before checking in")
    print(f"# rise >= {args.rise} -> drum;  rise < {args.rise} and b1 >= {args.b1} -> speech")
    print("file,start_s,end_s,label")
    for src in zab_sources():
        wav = zab_full_wav(src)
        secs = zab_seconds(lab, wav, args.window)
        if args.raw:
            print(f"# {src.stem}", file=sys.stderr)
            for r in secs:
                print(f"#   {r['t']:6.1f}  b0={r['b0']:.4f} b1={r['b1']:.4f} b2={r['b2']:.4f} "
                      f"rise={r['rise']:.4f}", file=sys.stderr)
        klass = []
        for r in secs:
            if r["rise"] >= args.rise:
                klass.append("drum")
            elif r["b1"] >= args.b1:
                klass.append("speech")
            else:
                klass.append("quiet")
        # Runs, with short interruptions absorbed -- see the docstring.
        runs = []
        for i, k in enumerate(klass):
            if runs and runs[-1][0] == k:
                runs[-1][2] = i + 1
            else:
                runs.append([k, i, i + 1])
        changed = True
        while changed:
            changed = False
            for i in range(1, len(runs) - 1):
                if (runs[i][2] - runs[i][1]) * args.window < args.min_run and \
                        runs[i - 1][0] == runs[i + 1][0]:
                    runs[i - 1][2] = runs[i + 1][2]
                    del runs[i:i + 2]
                    changed = True
                    break
        for k, a, b in runs:
            span = (b - a) * args.window
            if k == "quiet" or span < args.min_seg:
                continue
            print(f"{src.stem},{a * args.window:g},{b * args.window:g},{k}")


## @brief Two candidates closer together than this are treated as one stroke.
CAND_REFRACTORY_S = 0.060
## @brief The rise a candidate needs. Deliberately far under any shipped flux
#         floor -- rejecting is quick and hunting is not, so the human pass
#         should read a list that is too long rather than search the audio for
#         what is missing.
CAND_RISE = 0.004


def zab_candidates(binary, wav, offset=0.0):
    """
    @brief Every plausible stroke instant in one segment, with a guess at its
           class.

    Peaks in band 0's rise and in band 2's rise, merged. Both are needed: band
    0 finds the mallet stroke on the big head and band 2 finds the stick
    stroke on the thin one, and the second is the point rather than a
    distraction -- confusion between the two is the number a band-0-only
    design exists to keep small, and it cannot be computed without the stick
    strokes labelled.

    A peak has to be a local maximum over the two frames either side, so one
    stroke's attack ramp does not become four candidates; two peaks within
    CAND_REFRACTORY_S are merged as one stroke, keeping the stronger and
    letting a mallet stroke win a tie, since a mallet stroke mislabelled as a
    stick stroke is the error that costs a real detection.

    The class is a guess from which band rose more. The ear decides.

    @param binary  Which pattern_lab build to run.
    @param wav     The cut segment.
    @param offset  Seconds the segment starts at, so the instants come out
                   absolute within the full recording.
    @return [(t_s, "boom"|"tapa")], in time order.
    """
    with tempfile.TemporaryDirectory() as td:
        prefix = Path(td) / "cand"
        run_dump(binary, wav, prefix)
        meta, band = read_band_dump(prefix)
    hop, rate = int(meta["hop"]), int(meta["rate"])
    rise = [[0.0] * 4]
    for i in range(1, len(band)):
        rise.append([max(0.0, band[i][k] - band[i - 1][k]) for k in range(4)])

    peaks = []
    for k in (0, 2):
        for i in range(2, len(rise) - 2):
            v = rise[i][k]
            if v < CAND_RISE:
                continue
            # A local maximum over the window either side, so one stroke's
            # attack ramp does not become four candidates.
            if any(rise[j][k] > v for j in range(i - 2, i + 3) if j != i):
                continue
            peaks.append((i, k, v))
    peaks.sort()

    out = []
    for i, k, v in peaks:
        t = offset + i * hop / rate
        # Same stroke seen in both bands, or the tail of the previous one.
        if out and t - out[-1][0] < CAND_REFRACTORY_S:
            if v > out[-1][2] or k == 0:
                out[-1] = (out[-1][0], k if v > out[-1][2] else out[-1][1], max(v, out[-1][2]))
            continue
        out.append((t, k, v))
    return [(t, "boom" if k == 0 else "tapa") for t, k, _ in out]


def write_click_track(wav, cands, offset, dst):
    """
    @brief The segment in one ear, a click at each candidate in the other.

    The whole verification interface, and one file rather than a UI because
    the judgement being asked for -- did that click land on a stroke, and was
    it the right kind -- is a listening task. The two classes click at
    different pitches, so a mislabelled stroke is audible rather than needing
    to be looked up.

    @param wav     The cut segment; 16-bit PCM.
    @param cands   As zab_candidates() returns them.
    @param offset  The segment's start, subtracted to place the clicks.
    @param dst     Where to write the stereo result.
    """
    with wave.open(str(wav), "rb") as r:
        rate, ch, width = r.getframerate(), r.getnchannels(), r.getsampwidth()
        n = r.getnframes()
        raw = r.readframes(n)
    if width != 2:
        raise SystemExit(f"{wav}: expected 16-bit PCM")
    pcm = list(struct.unpack(f"<{len(raw) // 2}h", raw))
    left = [pcm[i * ch] for i in range(n)] if ch > 1 else pcm[:]

    right = [0] * n
    dur = int(0.004 * rate)
    for t, klass in cands:
        start = int((t - offset) * rate)
        f = 2400.0 if klass == "boom" else 5200.0
        for j in range(dur):
            i = start + j
            if 0 <= i < n:
                env = 1.0 - j / dur
                right[i] = max(-32768, min(32767,
                              right[i] + int(9000 * env * math.sin(2 * math.pi * f * j / rate))))
    with wave.open(str(dst), "wb") as o:
        o.setnchannels(2)
        o.setsampwidth(2)
        o.setframerate(rate)
        o.writeframes(struct.pack(f"<{2 * n}h",
                                  *[v for pair in zip(left, right) for v in pair]))


def read_labels():
    """
    @brief Read the hand-verified stroke table.
    @return {stem: [(t_s, class)]}, each list sorted; empty before the table
            exists.
    """
    out = {}
    if not ZAB_LABELS.exists():
        return out
    for line in ZAB_LABELS.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("file,"):
            continue
        stem, t, klass = line.rsplit(",", 2)
        out.setdefault(stem, []).append((float(t), klass))
    for v in out.values():
        v.sort()
    return out


def cmd_label(args):
    """
    @brief Generate candidates and click tracks for the human pass.

    Instants are absolute seconds into the full recording rather than offsets
    into a segment, so moving a segment boundary later does not silently shift
    every label inside it. A recording that already has labels is skipped
    unless --force.

    @param args  Parsed arguments: track, hop, out, force.
    """
    lab = build_lab(args.hop)
    have = read_labels()
    rows = [r for r in zab_segment_rows() if r[3] == "drum"]
    if args.track:
        rows = [r for r in rows if args.track.lower() in r[0].lower()]
    if not rows:
        raise SystemExit("no drum segments match --track")
    by_stem = {p.stem: p for p in zab_sources()}

    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)
    written = []
    for stem, start, end, _ in rows:
        if stem in have and not args.force:
            print(f"skip {stem} [{start:g}-{end:g}] -- already in {ZAB_LABELS.name} "
                  f"({len(have[stem])} rows); --force to regenerate", file=sys.stderr)
            continue
        src = by_stem[stem]
        wav = zab_cut(src, start, end)
        cands = zab_candidates(lab, wav, offset=start)
        click = outdir / f"{stem}.{start:g}-{end:g}.click.wav"
        write_click_track(wav, cands, start, click)
        written.append((stem, start, end, cands, click))
        print(f"{stem} [{start:g}-{end:g}]  {len(cands)} candidates  -> {click}",
              file=sys.stderr)

    if not written:
        return
    print("file,t_s,class")
    for stem, _, _, cands, _ in written:
        for t, klass in cands:
            print(f"{stem},{t:.3f},{klass}")


def cmd_sweep(args):
    """
    @brief The flux floor ladder: one row per floor per group, plus the control.
    @param args  Parsed arguments: groups, detector, hop, hist, floors.
    """
    lab = build_lab(args.hop, args.hist)
    tracks = corpus(args.groups)
    control = corpus(["control"])[0]
    key = "boom" if args.detector == "boom" else "beat"
    print(f"# {args.detector} flux floor, hop {args.hop}"
          + (f", BEAT_HIST {args.hist}" if args.hist else ""))
    print()
    print("| Floor | Set | rate/min | marginal/frame (median) | marginal range | control |")
    print("|---|---|---|---|---|---|")
    for floor in args.floors:
        flag = ["--boom-floor", str(floor)] if key == "boom" else ["--beat-floor", str(floor)]
        rows = measure_all(tracks, lab, flag)
        cr = measure(control, lab, flag)
        for group in args.groups:
            g = [r for r in rows if r["group"] == group]
            if not g:
                continue
            rate = [r["booms_min"] if key == "boom" else r["onsets_min"] for r in g]
            marg = [100 * r[f"marginal_{key}"] for r in g]
            cnt = cr["booms"] if key == "boom" else cr["onsets"]
            print(f"| {floor} | {group} | {rng_str(rate)} | {med(marg):.1f}% | "
                  f"{rng_str(marg, '{:.1f}')}% | {cnt} |")


def cmd_hist(args):
    """
    @brief BEAT_HIST on both of its axes at once.

    Left half: what the music says -- rate, marginal frames, and how noisy the
    threshold estimate is. Right half: what a lost frame costs, from converge,
    which the corpus cannot see at all. The two axes have to be read together,
    since BEAT_HIST is a frame count and the wall-clock it spans moves with
    the hop.

    @param args  Parsed arguments: groups, hop, hists, gap.
    """
    tracks = corpus(args.groups)
    print(f"# BEAT_HIST at hop {args.hop}")
    print()
    print("| HIST | span | onsets/min | booms/min | marginal beat | marginal boom "
          "| threshold sd | converge p50 | p95 | p95 ms | clean trials |")
    print("|---|---|---|---|---|---|---|---|---|---|---|")
    probe_csv = None
    for hist in args.hists:
        lab = build_lab(args.hop, hist)
        rows = measure_all(tracks, lab)
        span_ms = hist * args.hop * 1000.0 / RATE

        # One trace for the probe, written once and reused at every HIST. The
        # bands are an output of the FFT and the band edges, neither of which
        # BEAT_HIST touches, so re-deriving them per row would only introduce a
        # second thing that moves.
        probe_csv = CACHE / f"probe.hop{args.hop}.csv"
        if not probe_csv.exists():
            run_lab(lab, tracks[0].wav, probe_csv)
        conv = subprocess.run(
            [str(build_converge(hist, args.hop)), str(probe_csv),
             "--detector", "beat", "--gap", str(args.gap)],
            capture_output=True, text=True, check=True).stdout.split()
        c = dict(kv.split("=", 1) for kv in conv)

        print(f"| {hist} | {span_ms:.0f} ms | "
              f"{med([r['onsets_min'] for r in rows]):.1f} | "
              f"{med([r['booms_min'] for r in rows]):.1f} | "
              f"{med([100*r['marginal_beat'] for r in rows]):.1f}% | "
              f"{med([100*r['marginal_boom'] for r in rows]):.1f}% | "
              f"{med([r['thr_sd'] for r in rows]):.5f} | "
              f"{c['converge_p50']} | {c['converge_p95']} | {c['converge_p95_ms']} | "
              f"{c['clean_trials']} |")


def build_converge(hist, hop):
    """
    @brief Build one converge per (hist, hop) and cache it. @see build_lab
    @param hist  BEAT_HIST to build with.
    @param hop   DF_HOP_N to build with; analysis.hpp static_asserts on it.
    @return Path to the cached binary.
    """
    out = CACHE / "bin" / f"converge.hop{hop}.hist{hist}"
    if out.exists() and out.stat().st_mtime >= newest_source(HERE, ROOT / "components" / "dancefloor_leds"):
        return out
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["make", "-C", str(HERE), "clean"], check=True, stdout=subprocess.DEVNULL)
    subprocess.run(["make", "-C", str(HERE), f"HIST={hist}", f"HOP={hop}"],
                   check=True, stdout=subprocess.DEVNULL)
    shutil.copy2(HERE / "converge", out)
    subprocess.run(["make", "-C", str(HERE), "clean"], check=True, stdout=subprocess.DEVNULL)
    return out


def cmd_instants(args):
    """
    @brief Whether halving the hop is the same detector on a finer grid, or a
           different one with a similar count.

    Counts alone cannot tell those apart, since a matched count with shifted
    timing is a different detector. So every hop-1024 boom is matched to the
    nearest hop-512 boom and the distances are reported, one hop and one
    window being the two thresholds that mean something. Unmatched in the
    other direction -- a hop-512 boom with nothing near it at 1024 -- is the
    extra sensitivity, which is expected and is not a failure.

    @param args  Parsed arguments: boom_floor, hist.
    """
    flags = []
    if args.boom_floor is not None:
        flags = ["--boom-floor", str(args.boom_floor)]
    coarse = build_lab(1024, args.hist)
    fine = build_lab(512, args.hist)
    tracks = corpus(["anchor"])
    print("| Track | booms 1024 | booms 512 | within 12 ms | within 23 ms | median dt | "
          "unmatched 1024 | unmatched 512 |")
    print("|---|---|---|---|---|---|---|---|")
    tot = [0, 0, 0, 0, 0, 0]
    for t in tracks:
        a = measure(t, coarse, flags)["boom_at"]
        b = measure(t, fine, flags)["boom_at"]
        d = [min((abs(x - y) for y in b), default=9.9) for x in a]
        w12 = sum(1 for x in d if x <= 0.012)
        w23 = sum(1 for x in d if x <= 0.023)
        # The other direction: a hop-512 boom with no hop-1024 boom near it.
        e = [min((abs(y - x) for x in a), default=9.9) for y in b]
        u512 = sum(1 for x in e if x > 0.023)
        print(f"| {t.label} | {len(a)} | {len(b)} | {100*w12/max(1,len(a)):.0f}% | "
              f"{100*w23/max(1,len(a)):.0f}% | {1000*med(d):.0f} ms | "
              f"{len(a)-w23} | {u512} |")
        tot[0] += len(a); tot[1] += len(b); tot[2] += w12; tot[3] += w23
        tot[4] += len(a) - w23; tot[5] += u512
    print()
    print(f"totals: {tot[0]} booms at 1024, {tot[1]} at 512; "
          f"{100*tot[2]/max(1,tot[0]):.1f}% within one hop, "
          f"{100*tot[3]/max(1,tot[0]):.1f}% within one window; "
          f"{tot[4]} hop-1024 booms unmatched, {tot[5]} hop-512 booms new")


