#!/usr/bin/env python3
"""
sweep -- drive pattern_lab over the corpus and reduce its output to the tuning
tables.

Every number the detector tuning rests on is produced by a subcommand here, so
the command is the provenance. Nothing is written down that cannot be
regenerated by re-running the line that produced it.

Stdlib only, deliberately. This box has no numpy on either interpreter, and a
tool whose job is to still run in a year should not acquire a dependency in
order to compute a percentile.

  ./sweep.py manifest                       the corpus, with sha256s
  ./sweep.py control                        (re)generate the negative control
  ./sweep.py baseline                       reproduce the hop-1024 record
  ./sweep.py sweep --detector boom          the flux floor ladder
  ./sweep.py hist                           BEAT_HIST, both axes
  ./sweep.py segments                       propose the zabumba segment table
  ./sweep.py label                          candidates and a click track
  ./sweep.py instants                       boom instants, hop 1024 vs 512
"""

import argparse
import concurrent.futures
import hashlib
import math
import os
import random
import shutil
import struct
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

## @brief This file's directory; also where the checked-in tables live.
HERE = Path(__file__).resolve().parent
## @brief The dancefloor tree.
ROOT = HERE.parent.parent
## @brief The harness this drives.
LAB = ROOT / "tools" / "pattern_lab"

## @brief Lossless tracks, and the set the record was measured over.
ANCHOR_DIR = Path.home() / "dancefloor-tracks"
## @brief The wider lossy set, decoded on first use.
BREADTH_DIR = Path.home() / "Music" / "forro"
## @brief Isolated zabumba recordings, used in cut segments rather than whole.
ZABUMBA_DIR = Path.home() / "Music" / "zabumba"
## @brief Where decodes, cuts and built binaries are kept. DF_TUNING_CACHE
#         overrides it.
CACHE = Path(os.environ.get("DF_TUNING_CACHE", Path.home() / ".cache" / "dancefloor-tuning"))

# The zabumba material is cut into labelled segments rather than used whole:
# two of the six recordings are lessons, and one carries half a minute of pure
# talking that is worth keeping on purpose as a negative control. The tables
# are checked in beside this file because a segment boundary is a tuning input
# like any other -- `./sweep.py segments` shows how they were proposed, and
# what is checked in is what a human then confirmed by ear.

## @brief Segment boundaries, hand-confirmed. Written by hand from the output
#         of cmd_segments().
ZAB_SEGMENTS = HERE / "zabumba_segments.csv"
## @brief Stroke instants and classes, hand-confirmed against cmd_label()'s
#         click tracks. Absent until that pass has been done.
ZAB_LABELS = HERE / "zabumba_labels.csv"

## @brief df::RATE. Every decode is pinned to it.
RATE = 44100

## @brief The decode command, as a format template.
#
# Pinned to the firmware's rate and channel count rather than left to follow
# the source: pattern_lab analyses whatever rate the file carries, so a 48 kHz
# decode would move every band edge relative to the tuning.
FFMPEG = ["ffmpeg", "-v", "error", "-i", "{src}",
          "-ar", str(RATE), "-ac", "2", "-c:a", "pcm_s16le", "-y", "{dst}"]

## @brief How near the threshold counts as marginal, as a fraction of it.
#
# The firmware's own marginal test, from visualiser.cpp, counted PER FRAME.
# Per boom it would read as a threefold regression where there is none: the
# frame count doubled when the hop halved while the refractory period held the
# boom count nearly constant.
MARGIN = 0.1


class Track:
    """
    @brief One thing to measure: a whole recording, or a cut segment of one.
    """
    def __init__(self, label, source, wav, group, span=None):
        """
        @brief Build one.
        @param label   How it appears in a table.
        @param source  The file it came from, whatever container that was.
        @param wav     The decoded WAV pattern_lab is actually run over. The
                       same path as @p source for a lossless whole track.
        @param group   Which set it belongs to; the tables are grouped by it.
        @param span    (start_s, end_s) for a cut segment, else None.
        """
        ## @brief How this appears in a table.
        self.label = label
        ## @brief The file it came from, whatever container that was.
        self.source = source
        ## @brief The decoded WAV pattern_lab is run over.
        self.wav = wav
        ## @brief Which set it belongs to; the tables group by it.
        self.group = group
        ## @brief (start_s, end_s) for a cut segment, else None.
        self.span = span


def sha256(path):
    """
    @brief Hex sha256 of a file, read a megabyte at a time.
    @param path  The file.
    @return The digest.
    """
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def wav_info(path):
    """
    @brief A WAV's rate and duration.
    @param path  The file.
    @return (rate_hz, seconds).
    """
    with wave.open(str(path), "rb") as w:
        return w.getframerate(), w.getnframes() / w.getframerate()


def decode(src, dst):
    """
    @brief Decode anything ffmpeg reads into a WAV at the firmware's rate.
    @param src  The source file.
    @param dst  Where to write; parents are created, an existing file is
                overwritten.
    """
    dst.parent.mkdir(parents=True, exist_ok=True)
    cmd = [a.format(src=str(src), dst=str(dst)) for a in FFMPEG]
    subprocess.run(cmd, check=True)


def corpus(groups, quiet=False):
    """
    @brief The tracks in the named groups, decoding and caching as needed.

    The anchor set is read from the top level of its directory only. A nested
    xotes/ is excluded on purpose: most of its files are 44-byte headers with
    no audio and much of the rest is advertising, so an average over them
    would not mean anything.

    @param groups  Any of "anchor", "breadth", "control", "zabumba",
                   "zabumba-speech".
    @param quiet   Suppress the "decoding N tracks" note on stderr.
    @return A list of Track.
    """
    out = []
    if "anchor" in groups:
        # Top level only; see the docstring for why a nested xotes/ is out.
        for p in sorted(ANCHOR_DIR.glob("*.wav")):
            out.append(Track(p.stem, p, p, "anchor"))
    if "breadth" in groups:
        wavdir = CACHE / "wav"
        todo = []
        for p in sorted(BREADTH_DIR.glob("*.mp3")):
            dst = wavdir / (p.stem + ".wav")
            if not dst.exists():
                todo.append((p, dst))
            out.append(Track(p.stem, p, dst, "breadth"))
        if todo:
            if not quiet:
                print(f"decoding {len(todo)} tracks into {wavdir} ...", file=sys.stderr)
            with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count()) as ex:
                list(ex.map(lambda a: decode(*a), todo))
    if "control" in groups:
        p = CACHE / "control.wav"
        if not p.exists():
            make_control(p)
        out.append(Track("control (synthetic, no drum)", p, p, "control"))
    for g in ("zabumba", "zabumba-speech"):
        if g in groups:
            out.extend(zabumba_tracks("drum" if g == "zabumba" else "speech", g))
    return out


def zab_sources():
    """
    @brief The zabumba recordings, whatever container they arrived in.

    This is the only group with positive ground truth behind it, and the only
    one on which "did it fire on a drum stroke" is answerable at all -- on a
    full mix a rate ladder cannot tell a suppressed stroke from an absent one.
    It does not replace the anchor set, which is lossless and carries the
    comparison against the record; these are lossy rips through room and
    camera mics, and they answer a different question. Do not read one
    group's ladder as the other's.

    @return The source files, sorted.
    """
    return sorted(p for p in ZABUMBA_DIR.iterdir()
                  if p.suffix.lower() in (".opus", ".mp4", ".m4a", ".wav", ".mp3"))


def zab_full_wav(src):
    """
    @brief The whole recording at the firmware's rate, decoded once and cached.
    @param src  The source file.
    @return The cached WAV.
    """
    dst = CACHE / "wav" / "zabumba" / (src.stem + ".full.wav")
    if not dst.exists():
        decode(src, dst)
    return dst


def zab_cut(src, start, end):
    """
    @brief One segment, cut from the cached full decode and itself cached.

    Cut with the stdlib wave module rather than with ffmpeg -ss, so the
    boundary is an exact sample index rather than wherever the container's
    seek lands. ZAB_LABELS holds instants inside these cuts, so a boundary
    that moved by a few milliseconds between runs would silently shift every
    one of them.

    @param src    The source recording.
    @param start  Seconds into it.
    @param end    Seconds into it; clamped to the end of the file.
    @return The cut WAV.
    """
    dst = CACHE / "wav" / "zabumba" / f"{src.stem}.{start:g}-{end:g}.wav"
    if dst.exists():
        return dst
    full = zab_full_wav(src)
    dst.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(full), "rb") as r:
        rate, ch, w = r.getframerate(), r.getnchannels(), r.getsampwidth()
        a, b = int(start * rate), int(end * rate)
        b = min(b, r.getnframes())
        r.setpos(a)
        frames = r.readframes(max(0, b - a))
    with wave.open(str(dst), "wb") as o:
        o.setnchannels(ch)
        o.setsampwidth(w)
        o.setframerate(rate)
        o.writeframes(frames)
    return dst


def zab_segment_rows():
    """
    @brief Read the checked-in segment table.
    @return [(stem, start_s, end_s, label)], empty before the table exists.
    """
    if not ZAB_SEGMENTS.exists():
        return []
    rows = []
    for line in ZAB_SEGMENTS.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("file,"):
            continue
        stem, start, end, label = line.split(",")
        rows.append((stem, float(start), float(end), label))
    return rows


def zabumba_tracks(label, group):
    """
    @brief Cut every segment carrying one label into a Track.
    @param label  "drum" or "speech", matched against the segment table.
    @param group  The group name to tag the tracks with.
    @return A list of Track.
    """
    by_stem = {p.stem: p for p in zab_sources()}
    out = []
    for stem, start, end, lab in zab_segment_rows():
        if lab != label:
            continue
        src = by_stem.get(stem)
        if src is None:
            raise SystemExit(f"{ZAB_SEGMENTS}: no recording named {stem!r} in {ZABUMBA_DIR}")
        out.append(Track(f"{stem} [{start:g}-{end:g}]", src,
                         zab_cut(src, start, end), group, (start, end)))
    return out


def make_control(path, seconds=30):
    """
    @brief Synthesise the negative control: music with no drum anywhere in it.

    This is the acceptance test at the low end of the ladder. Without it
    "lower floor -> more booms" has no cost attached, because nothing says
    what the extra sensitivity is firing on.

    It is not silence with a beep. The bass CHANGES -- a left hand moving
    every two bars gives band 0 genuine rises to be wrong about -- and a
    triangle puts continuous energy in the top band at eighth-note rate, which
    is exactly what the boom detector exists to ignore. A floor that fires
    here is following the music rather than the drum.

    Two details in the synthesis are corrections rather than choices, and both
    are load-bearing. Phase is INTEGRATED rather than computed as f*t, and the
    triangle gets a 3 ms attack rather than being switched on: a step
    discontinuity is broadband, so a note change or a gated 6.3 kHz sine dumps
    energy straight into band 0 and the detector fires on it -- correctly. And
    the level is calibrated rather than picked, to put band 0's median where
    the anchor corpus sits; ten times that and a steady sine's own leakage
    ripple swings the band by the whole flux floor, so the control measures
    its own synthesis instead of the detector.

    @param path     Where to write the WAV; parents are created.
    @param seconds  How long to make it.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20260804)              # seeded: the sha256 is in the manifest
    n = seconds * RATE
    bass_notes = [55.0, 61.74, 49.0, 65.41]    # A1, B1, G1, C2 -- inside band 0
    frames = bytearray()
    phase_bass = 0.0
    phase_tri = 0.0
    for i in range(n):
        t = i / RATE
        # A note every 500 ms, each with a 30 ms attack and a slow decay. This
        # is the part that gives the control teeth: a bass note starting IS a
        # rise in band 0, and it is not a drum. A drone would have been silent
        # at every floor and would have proved nothing. 30 ms is a plucked or
        # bowed bass; a zabumba's mallet stroke is nearer 5, and telling those
        # apart is what the floor is being asked to do.
        note_t = t % 0.5
        f0 = bass_notes[int(t / 0.5) % len(bass_notes)]
        note_env = min(1.0, note_t / 0.030) * math.exp(-note_t * 1.2)
        phase_bass += 2 * math.pi * f0 / RATE
        phase_tri += 2 * math.pi * 6300.0 / RATE
        env = 0.0137 * (0.95 + 0.05 * math.sin(2 * math.pi * 0.3 * t)) * note_env
        v = env * math.sin(phase_bass)
        v += 0.5 * env * math.sin(3 * phase_bass)            # reedy, not pure
        # Right hand, well above band 0.
        for h in (392.0, 493.88, 587.33):
            v += 0.05 * math.sin(2 * math.pi * h * t)
        # Triangle: eighths at 120 BPM, 3 ms attack then decay, 6.3 kHz.
        ph = t % 0.25
        if ph < 0.12:
            attack = min(1.0, ph / 0.003)
            v += 0.10 * attack * math.exp(-ph * 30.0) * math.sin(phase_tri)
        v += rng.uniform(-1.0, 1.0) * 0.0005                 # dither
        s = max(-32768, min(32767, int(v * 20000)))
        frames += struct.pack("<hh", s, s)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(bytes(frames))
    print(f"wrote {path} ({seconds} s)", file=sys.stderr)


def newest_source(*dirs):
    """
    @brief mtime of the most recently touched file that goes into a host binary.

    The caches below are keyed on (hop, hist) alone, which is not enough on
    its own: a component that grows a feature leaves every cached binary
    predating it, and a sweep run afterwards measures the previous month's
    detector while reporting it as today's. A cached artefact older than its
    sources is the one failure mode a tuning harness cannot be allowed to
    have, since nothing about the output says which code produced it.

    @param dirs  Directories to scan; each is also scanned for an include/.
    @return The newest mtime found, or 0.0 for no sources at all.
    """
    newest = 0.0
    for d in dirs:
        for pat in ("*.c", "*.cpp", "*.h", "*.hpp", "Makefile"):
            for f in list(d.glob(pat)) + list((d / "include").glob(pat)):
                newest = max(newest, f.stat().st_mtime)
    return newest


def build_lab(hop, hist=None):
    """
    @brief Build one pattern_lab per (hop, hist) and cache it.

    Cached because a sweep would otherwise rebuild the same binary once per
    row. The build is bracketed by `make clean` on both sides, since HOP and
    HIST reach the object files and a stale one would link a disagreeing
    struct.

    @param hop   DF_HOP_N to build with.
    @param hist  BEAT_HIST to build with; None leaves the header's default.
    @return Path to the cached binary.
    """
    tag = f"hop{hop}" + (f".hist{hist}" if hist else "")
    out = CACHE / "bin" / f"pattern_lab.{tag}"
    if out.exists() and out.stat().st_mtime >= newest_source(LAB, ROOT / "components" / "dancefloor_leds"):
        return out
    out.parent.mkdir(parents=True, exist_ok=True)
    args = ["make", "-C", str(LAB), f"HOP={hop}"]
    if hist:
        args.append(f"HIST={hist}")
    subprocess.run(["make", "-C", str(LAB), "clean"], check=True, stdout=subprocess.DEVNULL)
    subprocess.run(args, check=True, stdout=subprocess.DEVNULL)
    shutil.copy2(LAB / "pattern_lab", out)
    subprocess.run(["make", "-C", str(LAB), "clean"], check=True, stdout=subprocess.DEVNULL)
    return out


def run_lab(binary, wav, csv, flags=()):
    """
    @brief Run pattern_lab over one file and write its per-frame CSV.
    @param binary  Which build to run.
    @param wav     The track.
    @param csv     Where the trace goes.
    @param flags   Extra arguments, typically a tuning override.
    """
    subprocess.run([str(binary), str(wav), "--no-tty", "--csv", str(csv), *flags],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def run_dump(binary, wav, prefix):
    """
    @brief Run pattern_lab over one file and write its per-frame binary dump.
    @param binary  Which build to run.
    @param wav     The track.
    @param prefix  The PREFIX the four dump files are written under.
    """
    subprocess.run([str(binary), str(wav), "--no-tty", "--dump", str(prefix)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def read_band_dump(prefix):
    """
    @brief Frame::band per frame, from a pattern_lab --dump.

    The other reader of this format is tools/pattern_lab/dump_load.py, which
    needs numpy and says so. This one does not: four float32 per frame is a
    struct.unpack, and everything here has to keep running on the stdlib.
    Both check the size against the .meta sidecar, so a truncated file is
    caught here for the same reason it is caught there.

    @param prefix  The PREFIX passed to --dump.
    @return (meta, band), band being a list of four-float tuples per frame.
    """
    meta = {}
    for line in Path(str(prefix) + ".meta").read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            meta[k.strip()] = v.strip()
    frames, bins = int(meta["frames"]), int(meta["band_bins"])
    raw = Path(str(prefix) + ".band.bin").read_bytes()
    want = frames * bins * 4
    if len(raw) != want:
        raise SystemExit(f"{prefix}.band.bin: {len(raw)} bytes, expected {want}")
    flat = struct.unpack(f"<{frames * bins}f", raw)
    return meta, [flat[i * bins:(i + 1) * bins] for i in range(frames)]


def metrics(csv):
    """
    @brief Everything a table needs, from one pass over a trace.

    Counted from the CSV rather than from pattern_lab's stderr summary, so the
    boom count and the marginal rate are known to come from the same frames.

    @param csv  A pattern_lab --csv.
    @return A dict of counts, rates, flux percentiles and firing instants.
    """
    frames = 0
    booms = onsets = 0
    marg_boom = marg_beat = 0
    boom_flux = []
    boom_thr = []
    boom_at = []
    onset_at = []
    with open(csv) as f:
        for line in f:
            if line[0] == "#" or line[0] == "b":       # header comment, column header
                continue
            c = line.rstrip("\n").split(",")
            if len(c) < 14:
                continue
            frames += 1
            t = float(c[1])
            flux, thr = float(c[6]), float(c[7])
            bflux, bthr = float(c[10]), float(c[11])
            if c[8] == "1":
                onsets += 1
                onset_at.append(t)
            if c[12] == "1":
                booms += 1
                boom_at.append(t)
            if bthr > 0 and abs(bflux - bthr) < MARGIN * bthr:
                marg_boom += 1
            if thr > 0 and abs(flux - thr) < MARGIN * thr:
                marg_beat += 1
            boom_flux.append(bflux)
            boom_thr.append(bthr)
    return {
        "frames": frames,
        "booms": booms,
        "onsets": onsets,
        "marginal_boom": marg_boom / frames if frames else 0.0,
        "marginal_beat": marg_beat / frames if frames else 0.0,
        "flux_p50": pctile(boom_flux, 0.50),
        "flux_p90": pctile(boom_flux, 0.90),
        "flux_p99": pctile(boom_flux, 0.99),
        "thr_sd": sd(boom_thr),
        "boom_at": boom_at,
        "onset_at": onset_at,
    }


def pctile(v, p):
    """
    @brief A percentile, by nearest rank.
    @param v  The values; not modified.
    @param p  0..1.
    @return The value at that rank, or 0.0 for an empty input.
    """
    if not v:
        return 0.0
    s = sorted(v)
    i = max(0, math.ceil(p * len(s)) - 1)
    return s[i]


def sd(v):
    """
    @brief Population standard deviation.
    @param v  The values.
    @return The deviation, or 0.0 for fewer than two values.
    """
    if len(v) < 2:
        return 0.0
    m = sum(v) / len(v)
    return math.sqrt(sum((x - m) ** 2 for x in v) / len(v))


def per_min(count, wav):
    """
    @brief Turn a count over a whole file into a rate per minute.
    @param count  How many.
    @param wav    The file they were counted over.
    @return Events per minute, or 0.0 for an empty file.
    """
    _, secs = wav_info(wav)
    return count * 60.0 / secs if secs else 0.0


def measure(track, binary, flags=()):
    """
    @brief Run one track through pattern_lab and reduce it to one row.
    @param track   What to measure.
    @param binary  Which build to run.
    @param flags   Extra arguments, typically a tuning override.
    @return metrics(), plus the duration, the two per-minute rates, and the
            track's label and group.
    """
    with tempfile.NamedTemporaryFile(suffix=".csv", delete=False) as tf:
        csv = Path(tf.name)
    try:
        run_lab(binary, track.wav, csv, flags)
        m = metrics(csv)
    finally:
        csv.unlink(missing_ok=True)
    _, secs = wav_info(track.wav)
    m["secs"] = secs
    m["booms_min"] = m["booms"] * 60.0 / secs if secs else 0.0
    m["onsets_min"] = m["onsets"] * 60.0 / secs if secs else 0.0
    m["label"] = track.label
    m["group"] = track.group
    return m


def measure_all(tracks, binary, flags=(), jobs=None):
    """
    @brief measure() over a list of tracks, in parallel.
    @param tracks  What to measure.
    @param binary  Which build to run.
    @param flags   Extra arguments, passed to every run.
    @param jobs    Workers; defaults to two fewer than the CPU count, so a
                   sweep leaves the machine usable.
    @return One row per track, in order.
    """
    jobs = jobs or max(1, os.cpu_count() - 2)
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as ex:
        return list(ex.map(lambda t: measure(t, binary, flags), tracks))


def rng_str(vals, fmt="{:.0f}"):
    """
    @brief Format a min-max range for a table cell.
    @param vals  The values.
    @param fmt   Format string for each end.
    @return "lo-hi", or "-" for an empty input.
    """
    if not vals:
        return "-"
    return f"{fmt.format(min(vals))}-{fmt.format(max(vals))}"


def med(vals):
    """
    @brief The median.
    @param vals  The values.
    @return pctile(vals, 0.50).
    """
    return pctile(vals, 0.50)


def cmd_manifest(args):
    """
    @brief Print the corpus as a markdown table, with sha256s.

    A segment's source digest is shared with its siblings and so does not
    identify the material a label is keyed to; the cut's own digest does, and
    that is what the segment rows carry. The source recordings are listed
    separately underneath.

    @param args  Parsed arguments; only args.groups is read.
    """
    tracks = corpus(args.groups)
    print("| Track | Set | Source | s | Hz | sha256 |")
    print("|---|---|---|---|---|---|")
    for t in tracks:
        rate, secs = wav_info(t.wav)
        if t.span:
            kind = f"{t.source.suffix.lstrip('.')}, cut {t.span[0]:g}-{t.span[1]:g} s"
            digest = sha256(t.wav)
        else:
            kind = "wav" if t.source.suffix == ".wav" else "mp3, decoded"
            digest = sha256(t.source)
        print(f"| {t.label} | {t.group} | {kind} | {secs:.0f} | {rate} | {digest} |")
    if any(t.span for t in tracks):
        print()
        print("Segment sha256s are of the cut WAV, since the labels are instants")
        print("inside it. Source recordings:")
        print()
        print("| Recording | s | sha256 (source) |")
        print("|---|---|---|")
        for src in zab_sources():
            _, secs = wav_info(zab_full_wav(src))
